const DAY_MS = 86400000, EPOCH = Date.UTC(2026, 0, 1);
// today's day (UTC) as YYYY-MM-DD, and the prompt for any such day
export const todayKey = (t = Date.now()) => new Date(t).toISOString().slice(0, 10);
export function promptFor(day) { const n = Math.round((Date.parse(day + 'T00:00:00Z') - EPOCH) / DAY_MS); return PROMPTS[((n % PROMPTS.length) + PROMPTS.length) % PROMPTS.length]; }
export const todaysPrompt = () => promptFor(todayKey());
// a day as people say it: "4 November"
export const dayWords = day => new Date(day + 'T12:00:00Z').toLocaleDateString(undefined, { day: 'numeric', month: 'long', timeZone: 'UTC' });
